inline float textWidth (const juce::String& s, float px) { return s.isEmpty() ? 0.0f : (6.0f * (float) s.length() - 1.0f) * px; }

inline void drawText (juce::Graphics& g, const juce::String& text, float x, float y, float px)
{
    for (auto ch : text.toUpperCase())
    {
        auto it = font().find (ch);
        if (it != font().end())
            for (int r = 0; r < 7; ++r)
                for (int c = 0; c < 5; ++c)
                    if (it->second[(size_t) r][c] == '#')
                        inkPixel (g, x + (float) c * px, y + (float) r * px, px);
        x += 6.0f * px;
    }
}

