// cheap deterministic hash for "rough print" jitter
inline float hash01 (int x, int y)
{
    uint32_t h = (uint32_t) x * 374761393u + (uint32_t) y * 668265263u;
    h = (h ^ (h >> 13)) * 1274126177u;
    return (float) ((h ^ (h >> 16)) & 0xffff) / 65535.0f;
}

// One printed pixel: slightly oversized (ink bleed) with tiny irregularities.
inline void inkPixel (juce::Graphics& g, float x, float y, float s)
{
    const float j = hash01 ((int) (x * 7.0f), (int) (y * 13.0f));
    const float grow = 0.06f + 0.12f * j;   // tight, crisp: pixels just touch
    g.fillRect (x - grow * 0.5f, y - grow * 0.5f, s + grow, s + grow);
}

