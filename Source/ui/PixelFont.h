inline void drawLogo (juce::Graphics& g, const juce::String& text, float x, float y, float px)
{
    for (auto ch : text)
    {
        auto it = logoFont().find (ch);
        if (it != logoFont().end())
            for (int r = 0; r < 11; ++r)
                for (int c = 0; c < 7; ++c)
                    if (it->second[(size_t) r][c] == '#')
                        inkPixel (g, x + (float) c * px, y + (float) r * px, px);
        x += 9.0f * px;
    }
}

enum class Align { left, centre, right };

inline void drawText (juce::Graphics& g, const juce::String& text, float x, float y, float px, Align a)
{
    const float w = textWidth (text, px);
    if (a == Align::centre) x -= w * 0.5f;
    if (a == Align::right)  x -= w;
    drawText (g, text, std::round (x), y, px);
}

inline void dashedLine (juce::Graphics& g, float x0, float x1, float y, float dash = 4.0f, float gap = 4.0f)
{
    for (float x = x0; x < x1; x += dash + gap)
        g.fillRect (x, y, std::min (dash, x1 - x), 1.5f);
}
